"""Generate the applet/popup background at the theme's own corner radius.

`widgets/background` is the frame behind every Plasma popup — the notification
history, the tray, Kickoff, the widget explorer — because `PlasmaComponents`
`Dialog`/`Popup`/`Drawer` and `PlasmaCore.DialogBackground` all draw it. Breeze's
copy uses a 4px corner inside a 4px border with 14px content insets, so on our
14px panel and 15px pill language those popups read as square surfaces with a
short nub and a visible 1px seam (captured 2026-11-16).

This builds the same nine-slice frame at R=14 with a 1px `ColorScheme-Frame` band
following the contour, keeps Breeze's 14px content insets (so popup layout is
unchanged) and carries Breeze's `shadow-*` slices through verbatim, so popups
keep their shadow. The `toolbutton-*` state elements are dropped: in Plasma 6 an
applet button draws `widgets/button`, not a prefixed applet background.

Usage:
    applet-background.py [--check] [path/to/widgets/background.svgz ...]
"""

from __future__ import annotations

import gzip
import importlib.util
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
BASELINE = ROOT / "upstream" / "plasma" / "desktoptheme" / "default" / "widgets" / "background.svgz"
CORNER_TOOL = HERE / "round-panel-corners.py"
SLOTS = [(v, s) for v in ("mt-nightshift", "mt-dayshift") for s in ("", "solid", "translucent")]
DEFAULT = [ROOT / "themes" / v / s / "widgets" / "background.svgz" for v, s in SLOTS]

R = 14          # corner radius and border thickness
C = 32          # centre slice
W = H = 2 * R + C
MARGIN = 14     # content inset, Breeze's value for applets

HEADER = ("<!--\n"
          "  MT Nightshift applet background. Frame regenerated at a 14px corner radius with a\n"
          "  1px ColorScheme-Frame band; content insets are Breeze's 14px and the shadow slices\n"
          "  are copied from Breeze's widgets/background.svgz (LGPL-2.0-or-later, KDE Visual\n"
          "  Design Group). Generated by tools/plasma-theme/applet-background.py; do not edit.\n"
          "-->\n")


def read(path: Path) -> str:
    """Reads an SVG or gzipped SVGZ as text."""
    raw = path.read_bytes()
    return (gzip.decompress(raw) if raw[:2] == b"\x1f\x8b" else raw).decode()


def encode(text: str) -> bytes:
    """Writes gzip with a fixed mtime so output is byte-stable."""
    return gzip.compress(text.encode(), mtime=0)


def group_span(text: str, ident: str) -> tuple[int, int] | None:
    """Returns the (start, end) offsets of a group's body, or None."""
    match = re.search(r'<g[^>]*id="%s"[^>]*>' % ident, text)
    if not match:
        return None
    start, depth, cursor = match.end(), 1, match.end()
    while depth:
        nxt = re.search(r"</?g\b", text[cursor:])
        if not nxt:
            return None
        here = cursor + nxt.start()
        depth += -1 if text[here:here + 2] == "</" else 1
        cursor = here + 2
    return start, cursor - len("</g")


def corners() -> tuple:
    """Imports the sampled corner builders shared with the panel generator."""
    spec = importlib.util.spec_from_file_location("panel_corners", CORNER_TOOL)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)  # type: ignore[union-attr]
    return module.face_corner, module.outline_corner


def frame() -> str:
    """Nine-slice frame at R, with strip bands and sampled corner bands."""
    face_corner, outline_corner = corners()
    bg = 'class="ColorScheme-Background" style="fill:currentColor"'
    fr = 'class="ColorScheme-Frame" style="fill:currentColor"'
    out = []

    def group(ident: str, tx: int, ty: int, body: str) -> None:
        out.append(f'  <g id="{ident}" transform="translate({tx},{ty})">\n{body}  </g>\n')

    group("top", R, 0,
          f'    <rect id="rect4152" {bg} width="{C}" height="{R}" x="0" y="0" />\n'
          f'    <rect {fr} x="0" y="0" width="{C}" height="1" />\n')
    group("bottom", R, R + C,
          f'    <rect id="rect4148" {bg} width="{C}" height="{R}" x="0" y="0" />\n'
          f'    <rect {fr} x="0" y="{R - 1}" width="{C}" height="1" />\n')
    group("left", 0, R,
          f'    <rect id="rect4144" {bg} width="{R}" height="{C}" x="0" y="0" />\n'
          f'    <rect {fr} x="0" y="0" width="1" height="{C}" />\n')
    group("right", R + C, R,
          f'    <rect id="rect4140" {bg} width="{R}" height="{C}" x="0" y="0" />\n'
          f'    <rect {fr} x="{R - 1}" y="0" width="1" height="{C}" />\n')
    group("center", R, R, f'    <rect id="rect4138" {bg} width="{C}" height="{C}" x="0" y="0" />\n')

    for ident, tx, ty, key in (("topleft", 0, 0, "tl"), ("topright", R + C, 0, "tr"),
                               ("bottomleft", 0, R + C, "bl"), ("bottomright", R + C, R + C, "br")):
        group(ident, tx, ty, face_corner(key, R) + outline_corner(key, R))

    hints = (
        f'  <rect id="hint-top-margin" x="20" y="0" width="4" height="{MARGIN}" style="fill:#ff6600" />\n'
        f'  <rect id="hint-bottom-margin" x="20" y="0" width="4" height="{MARGIN}" style="fill:#ff6600" />\n'
        f'  <rect id="hint-left-margin" x="0" y="30" width="{MARGIN}" height="4" style="fill:#ff6600" />\n'
        f'  <rect id="hint-right-margin" x="0" y="30" width="{MARGIN}" height="4" style="fill:#ff6600" />\n'
        f'  <rect id="hint-top-inset" x="20" y="0" width="4" height="1e-9" style="fill:#00ff00" />\n'
        f'  <rect id="hint-bottom-inset" x="20" y="0" width="4" height="1e-9" style="fill:#00ff00" />\n'
        f'  <rect id="hint-left-inset" x="0" y="30" width="1e-9" height="4" style="fill:#00ff00" />\n'
        f'  <rect id="hint-right-inset" x="0" y="30" width="1e-9" height="4" style="fill:#00ff00" />\n'
        f'  <rect id="hint-stretch-borders" x="20" y="10" width="5" height="4.375" style="fill:#008000" />\n'
    )
    return "".join(out) + hints


def shadows() -> str:
    """Breeze's shadow slices, verbatim."""
    text = read(BASELINE)
    out = []
    for ident in ("shadow-top", "shadow-right", "shadow-bottom", "shadow-left",
                  "shadow-topleft", "shadow-topright", "shadow-bottomleft", "shadow-bottomright",
                  "shadow-center"):
        span = group_span(text, ident)
        if not span:
            raise SystemExit("missing %s in the baseline" % ident)
        match = re.search(r'<g[^>]*id="%s"[^>]*>' % ident, text)
        out.append(text[match.start():span[1] + len("</g>")] + "\n")
    return "".join(out)


def build() -> str:
    """Complete document: frame + hints + shadows."""
    document = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        + HEADER
        + f'<svg xmlns="http://www.w3.org/2000/svg" width="{W + 120}" height="{H}" viewBox="0 0 {W + 120} {H}">\n'
        + '  <style type="text/css" id="current-color-scheme">\n'
        + '      .ColorScheme-Text { color:#E8EBF0; }\n'
        + '      .ColorScheme-Background { color:#101216; }\n'
        + '      .ColorScheme-Frame { color:#1B1D21; }\n'
        + '  </style>\n'
        + frame()
        + shadows()
        + '</svg>\n'
    )
    return document


def self_check(text: str) -> list[str]:
    """Corner artwork must span exactly the border it is stretched into."""
    problems = []
    for strip in ("top", "bottom", "left", "right"):
        span = group_span(text, strip)
        body = text[span[0]:span[1]]
        rect = re.search(r'<rect[^>]*width="(\d+)"[^>]*height="(\d+)"', body)
        if not rect:
            problems.append(f"{strip}: no fill rect")
            continue
        width, height = int(rect.group(1)), int(rect.group(2))
        want = R if strip in ("top", "bottom") else R
        if (strip in ("top", "bottom") and height != want) or (strip in ("left", "right") and width != want):
            problems.append(f"{strip}: thickness does not match the {R}px border")
    for corner in ("topleft", "topright", "bottomleft", "bottomright"):
        span = group_span(text, corner)
        body = text[span[0]:span[1]]
        numbers = [float(n) for n in re.findall(r"-?\d+\.?\d*", body)]
        if not numbers or abs(max(numbers) - R) > 0.51:
            problems.append(f"{corner}: artwork spans {max(numbers) if numbers else 0:g}px, border is {R}px")
    return problems


def main() -> int:
    """Writes or checks every slot."""
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    targets = [Path(a) for a in args] or DEFAULT

    document = build()
    problems = self_check(document)
    if problems:
        for problem in problems:
            print("FAIL " + problem)
        return 1

    stale = []
    for path in targets:
        current = read(path) if path.exists() else ""
        if current == document:
            print(f"unchanged {path.relative_to(ROOT)}")
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(encode(document))
        print(f"rewrote {path.relative_to(ROOT)}")

    if check:
        if stale:
            print("applet background is stale: %s" % ", ".join(stale))
            return 1
        print(f"{len(targets)} applet backgrounds match the generated frame")
    return 0


if __name__ == "__main__":
    sys.exit(main())
