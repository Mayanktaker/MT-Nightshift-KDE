"""Rebuild the dialog frame from Breeze's solid slice set, at Breeze's geometry.

The dialog asset is the frame every Plasma popup uses — notifications, trays,
KRunner, OSDs and `BackgroundMetrics`. The first derivation rebuilt its frame at
14px borders while Breeze's slice set is 6px, and drew the 1px Frame band as a
chord across each corner. On the notification popup that read as square corners
with a diagonal hairline (2026-11-15), and after the first repair — corners
regenerated at 6px inside a still-14px frame — as a corner smaller than its
border, which KSvg then stretched (2026-11-16).

So the file is no longer hand-derived: this tool takes the upstream solid slice
set verbatim (geometry, hints, masks, shadow), adds the 1px `ColorScheme-Frame`
band on the four strips, and takes the four corner bodies — face plus sampled
band, both about the same arc — from the tooltip asset, which menus already
render with cleanly. Corner geometry is therefore 6px everywhere and identical
to the tooltip by construction.

Usage:
    dialog-frame.py [--check] [path/to/dialogs/background.svgz ...]

Without paths every variant and every lookup slot is written; --check compares
in memory and exits non-zero on drift, so `make check` guards the result.
"""

from __future__ import annotations

import gzip
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
BASELINE = ROOT / "upstream" / "plasma" / "desktoptheme" / "default" / "solid" / "dialogs" / "background.svgz"
TOOLTIP = ROOT / "themes" / "mt-nightshift" / "widgets" / "tooltip.svgz"
CORNERS = ("topleft", "topright", "bottomleft", "bottomright")
SLOTS = [(variant, slot)
         for variant in ("mt-nightshift", "mt-dayshift")
         for slot in ("", "solid", "translucent")]
DEFAULT = [ROOT / "themes" / v / s / "dialogs" / "background.svgz" for v, s in SLOTS]

HEADER = ("<!--\n"
          "  MT Nightshift frame asset. Derived from KDE Breeze solid/dialogs/background.svgz\n"
          "  (LGPL-2.0-or-later, KDE Visual Design Group); frame geometry, slice names and\n"
          "  opaque \"solid\" fills are Breeze's. Modification: a 1px ColorScheme-Frame outline\n"
          "  is drawn inside the frame contour as filled geometry, and the four corner bodies\n"
          "  are the tooltip's 6px construction, so no band can cross a corner as a chord.\n"
          "  Generated by tools/plasma-theme/dialog-frame.py; do not hand-edit.\n"
          "-->\n")


def read(path: Path) -> str:
    """Reads an SVG or gzipped SVGZ as text."""
    raw = path.read_bytes()
    return (gzip.decompress(raw) if raw[:2] == b"\x1f\x8b" else raw).decode()


def encode(text: str) -> bytes:
    """Writes gzip with a fixed mtime so output is byte-stable."""
    return gzip.compress(text.encode(), mtime=0)


def group_span(text: str, ident: str) -> tuple[int, int]:
    """Returns the (start, end) offsets of a group's body."""
    match = re.search(r'<g[^>]*id="%s"[^>]*>' % ident, text)
    if not match:
        raise SystemExit("missing group %r" % ident)
    start, depth, cursor = match.end(), 1, match.end()
    while depth:
        nxt = re.search(r"</?g\b", text[cursor:])
        if not nxt:
            raise SystemExit("unbalanced group %r" % ident)
        here = cursor + nxt.start()
        depth += -1 if text[here:here + 2] == "</" else 1
        cursor = here + 2
    return start, cursor - len("</g")


def corner_bodies() -> dict[str, str]:
    """Corner bodies (face + sampled band) from the tooltip asset."""
    text = read(TOOLTIP)
    bodies = {}
    for corner in CORNERS:
        start, end = group_span(text, corner)
        body = text[start:end]
        body = re.sub(r'id="path\d+"', f'id="face-{corner}"', body, count=1)
        body = body.replace("<path ", f'<path id="outline-{corner}" ', 1) if 'outline-' not in body else body
        bodies[corner] = body
    return bodies


def band_rect(group: str, edge: str, width: int, height: int) -> str:
    """1px Frame band at the outer edge of one strip element."""
    style = 'class="ColorScheme-Frame" style="fill:currentColor"'
    if edge == "top":
        return f'    <rect {style} x="0" y="0" width="{width}" height="1" />\n'
    if edge == "bottom":
        return f'    <rect {style} x="0" y="{height - 1}" width="{width}" height="1" />\n'
    if edge == "left":
        return f'    <rect {style} x="0" y="0" width="1" height="{height}" />\n'
    return f'    <rect {style} x="{width - 1}" y="0" width="1" height="{height}" />\n'


def rect_size(body: str, label: str) -> tuple[int, int]:
    """Width and height of the first fill rect in a strip body."""
    rect = re.search(r"<rect[^>]*>", body)
    if not rect:
        raise SystemExit("no fill rect in the %s strip" % label)
    width = re.search(r'width="(\d+)"', rect.group(0))
    height = re.search(r'height="(\d+)"', rect.group(0))
    if not width or not height:
        raise SystemExit("incomplete fill rect in the %s strip" % label)
    return int(width.group(1)), int(height.group(1))


def build() -> str:
    """Baseline solid slices + strip bands + tooltip corners."""
    text = read(BASELINE)
    bodies = corner_bodies()

    for edge in ("top", "bottom", "left", "right"):
        start, end = group_span(text, edge)
        body = text[start:end]
        width, height = rect_size(body, edge)
        text = text[:start] + body.rstrip() + "\n" + band_rect(edge, edge, width, height) + text[end:]

    for corner in CORNERS:
        start, end = group_span(text, corner)
        text = text[:start] + bodies[corner] + text[end:]

    # Replace any existing MT header comment, then prepend ours.
    text = re.sub(r"<!--\n  MT Nightshift frame asset.*?-->\n", "", text, flags=re.S)
    return text.replace("<svg", HEADER + "<svg", 1) if "<svg" in text else text


def self_check(text: str) -> list[str]:
    """Corner artwork must be the same size as the strips it joins."""
    problems = []
    thickness = {}
    for edge in ("top", "bottom", "left", "right"):
        start, end = group_span(text, edge)
        thickness[edge] = rect_size(text[start:end], edge)
    for corner in CORNERS:
        start, end = group_span(text, corner)
        body = text[start:end]
        nums = [float(n) for n in re.findall(r"-?\d+\.?\d*", body.replace("e-", "e-"))]
        xs = [n for i, n in enumerate(nums)]
        # The face and band live in a local square whose size is the border.
        want = thickness["left"][0]
        span = max(max(nums), 0.0)
        if abs(span - want) > 0.51:
            problems.append(f"{corner}: artwork spans {span:g}px, border is {want}px")
    return problems


def main() -> int:
    """Writes or checks every slot."""
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    targets = [Path(a) for a in args] or DEFAULT

    document = build()
    problems = self_check(document)
    if problems:
        for problem in problems:
            print("FAIL " + problem)
        return 1

    stale = []
    for path in targets:
        current = read(path) if path.exists() else ""
        if current == document:
            print(f"unchanged {path.relative_to(ROOT)}")
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
            continue
        path.write_bytes(encode(document))
        print(f"rewrote {path.relative_to(ROOT)}")

    if check:
        if stale:
            print("dialog frame is stale: %s" % ", ".join(stale))
            return 1
        print(f"{len(targets)} dialog frames match the generated geometry")
    return 0


if __name__ == "__main__":
    sys.exit(main())
